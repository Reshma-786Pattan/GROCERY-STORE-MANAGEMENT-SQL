# Rank employees based on total sales revenue using RANK().

SELECT E.EMP_NAME ,RANK() OVER (ORDER BY SUM(TOTAL_PRICE)  DESC) AS EMPLOYEE_RANK
FROM ORDERS O
JOIN ORDER_DETAILS  OD
ON O.ORD_ID=OD.ORD_ID
JOIN EMPLOYEES E
ON E.EMP_ID=O.EMP_ID
GROUP BY E.EMP_ID;

# Find the second highest-selling product using DENSE_RANK().

SELECT * FROM
(
SELECT P.PROD_NAME,SUM(TOTAL_PRICE) AS TOTAL_REVENUE,DENSE_RANK() OVER (ORDER BY SUM(TOTAL_PRICE) DESC) AS PRODUCT_RANK
FROM PRODUCTS P
JOIN ORDER_DETAILS  OD
ON P.PROD_ID=OD.PROD_ID
GROUP BY OD.PROD_ID,P.PROD_NAME) AS SELLING_PRODUCT_PRICE
WHERE PRODUCT_RANK=2;






