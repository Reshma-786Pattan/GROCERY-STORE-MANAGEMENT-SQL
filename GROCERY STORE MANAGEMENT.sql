CREATE DATABASE GROCERY_STORE_MANAGEMENT;

USE GROCERY_STORE_MANAGEMENT;

-- Supplier Table

CREATE TABLE IF NOT EXISTS supplier (
    sup_id TINYINT AUTO_INCREMENT PRIMARY KEY,
    sup_name VARCHAR(255),
    address TEXT
);

-- Categories Table

CREATE TABLE IF NOT EXISTS categories (
    cat_id TINYINT AUTO_INCREMENT PRIMARY KEY,
    cat_name VARCHAR(255)
);

-- Employees Table

CREATE TABLE IF NOT EXISTS employees (
    emp_id TINYINT AUTO_INCREMENT PRIMARY KEY,
    emp_name VARCHAR(255),
    hire_date DATE
);


-- 4. Customers Table

CREATE TABLE IF NOT EXISTS customers (
    cust_id SMALLINT AUTO_INCREMENT PRIMARY KEY,
    cust_name VARCHAR(255),
    address TEXT
    );
    
    
-- 5. Products Table

CREATE TABLE IF NOT EXISTS products (
    prod_id TINYINT AUTO_INCREMENT PRIMARY KEY,
    prod_name VARCHAR(255),
    sup_id TINYINT,
    cat_id TINYINT,
    price DECIMAL(10,2),
    FOREIGN KEY (sup_id) REFERENCES supplier(sup_id)
        ON UPDATE CASCADE ON DELETE CASCADE,
    FOREIGN KEY (cat_id) REFERENCES categories(cat_id)
        ON UPDATE CASCADE ON DELETE CASCADE
);

-- 6. Orders Table

CREATE TABLE IF NOT EXISTS orders (
    ord_id SMALLINT AUTO_INCREMENT PRIMARY KEY,
    cust_id SMALLINT,
    emp_id TINYINT,
    order_date DATE,
    FOREIGN KEY (cust_id) REFERENCES customers(cust_id)
        ON UPDATE CASCADE ON DELETE CASCADE,
    FOREIGN KEY (emp_id) REFERENCES employees(emp_id)
        ON UPDATE CASCADE ON DELETE CASCADE
);


-- 7. Order_Details Table

CREATE TABLE IF NOT EXISTS order_details (
    ord_detID SMALLINT AUTO_INCREMENT PRIMARY KEY,
    ord_id SMALLINT,
    prod_id TINYINT,
    quantity TINYINT,
    each_price DECIMAL(10,2),
    total_price DECIMAL(10,2),
    FOREIGN KEY (ord_id) REFERENCES orders(ord_id)
        ON UPDATE CASCADE ON DELETE CASCADE,
    FOREIGN KEY (prod_id) REFERENCES products(prod_id)
        ON UPDATE CASCADE ON DELETE CASCADE
);


-- 1. CUSTOMER INSIGHTS

# How many unique customers have placed orders?

SELECT COUNT(DISTINCT(C.CUST_ID)) AS UNIQUE_CUSTOMER_ORDERS
FROM CUSTOMERS C
INNER JOIN ORDERS O
ON C.CUST_ID=O.CUST_ID;

# Which customers have placed the highest number of orders?

SELECT CUST_NAME,COUNT(O.ORD_ID) AS NUMBER_OF_ORDERS
FROM CUSTOMERS C
INNER JOIN ORDERS O
ON C.CUST_ID=O.CUST_ID
GROUP BY CUST_NAME
ORDER BY NUMBER_OF_ORDERS DESC
LIMIT 5;

# What is the total and average purchase value per customer?

SELECT O.CUST_ID,SUM(OD.TOTAL_PRICE) AS TOTAL_PURCHASE_VALUE,AVG(TOTAL_PRICE) AS AVERAGE_PURCHASE_VALUE
FROM ORDERS O
inner JOIN ORDER_DETAILS OD
ON O.ORD_Id=Od.ORD_Id
GROUP BY O.CUST_ID;

# Who are the top 5 customers by total purchase amount?

SELECT O.CUST_ID,C.CUST_NAME,SUM(OD.TOTAL_PRICE) AS TOTAL_PURCHASE_AMOUNT
FROM ORDERS O
JOIN ORDER_DETAILS OD
ON O.ORD_ID=OD.ORD_ID
JOIN CUSTOMERS C
ON C.CUST_ID=O.CUST_ID
GROUP BY O.CUST_ID
ORDER BY TOTAL_PURCHASE_AMOUNT DESC
LIMIT 5;


-- 2. Product Performance

# How many products exist in each category?

SELECT CAT_NAME,COUNT(P.PROD_ID) as TOTAL_NO_OF_PRODUCTS
FROM CATEGORIES C
INNER JOIN PRODUCTS P
ON C.CAT_ID=P.CAT_ID
GROUP BY CAT_NAME;

# What is the average price of products by category?

SELECT C.CAT_NAME,AVG(PRICE) AS AVERAGE_Product_PRICE
FROM CATEGORIES C
INNER JOIN PRODUCTS P
ON C.CAT_ID=P.CAT_ID
GROUP BY C.CAT_NAME;

# Which products have the highest total sales volume (by quantity)?

SELECT PROD_NAME,SUM(O.QUANTITY) AS QUANTITY
FROM PRODUCTS P
JOIN ORDER_DETAILS O
ON P.PROD_ID=O.PROD_ID
GROUP BY PROD_NAME
ORDER BY QUANTITY DESC;

# What is the total revenue generated by each product?

SELECT P.PROD_ID,P.PROD_NAME,SUM(total_price) as total_revenue
FROM ORDER_DETAILS OD
JOIN PRODUCTS P
ON OD.PROD_ID=P.PROD_ID
group by P.PROD_ID;

# How do product sales vary by category and supplier?

SELECT C.CAT_NAME,S.SUP_NAME,SUM(OD.TOTAL_PRICE)
FROM CATEGORIES C
JOIN PRODUCTS P
ON C.CAT_ID=P.CAT_ID
JOIN ORDER_DETAILS OD
ON OD.PROD_ID=P.PROD_ID
JOIN SUPPLIER S
ON S.SUP_ID=P.SUP_ID
GROUP BY C.CAT_NAME,S.SUP_NAME;


-- 3. Sales and Order Trends

# How many orders have been placed in total?

SELECT COUNT(ORD_ID)
FROM ORDERS;

# What is the average value per order?

SELECT AVG(TOTALORDER)
FROM 
(SELECT ORD_ID,SUM(TOTAL_PRICE) AS TOTALORDER
FROM ORDER_DETAILS
GROUP BY ORD_ID) AS PER_ORDER;

# On which dates were the most orders placed?

SELECT ORDER_DATE,COUNT(ORDER_DATE) AS No_of_Orders
FROM ORDERS
GROUP BY ORDER_DATE
ORDER BY No_of_Orders DESC;

# What are the monthly trends in order volume and revenue?

SELECT MONTHNAME(O.ORDER_DATE),SUM(QUANTITY),SUM(TOTAL_PRICE)
FROM ORDERS O
JOIN ORDER_DETAILS OD
ON O.ORD_ID=OD.ORD_ID
GROUP BY MONTHNAME(O.ORDER_DATE);

# How do order patterns vary across weekdays and weekends?

SELECT DAYNAME(O.ORDER_DATE) AS DAYNAMES,SUM(OD.QUANTITY) AS TOTAL_QUANTITY_PATTERNS,
IF (DAYNAME(O.ORDER_DATE) IN ("SATURDAY","SUNDAY"),"WEEKEND","WEEKDAY") AS DAY_TYPE
FROM ORDERS O
JOIN ORDER_DETAILS OD
ON O.ORD_ID=OD.ORD_ID 
GROUP BY DAYNAME(O.ORDER_DATE),
IF (DAYNAME(O.ORDER_DATE) IN ("SATURDAY","SUNDAY"),"WEEKEND","WEEKDAY")
ORDER BY DAY_TYPE;

